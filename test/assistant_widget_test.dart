import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:smogshield_ai/core/models/assistant_message.dart';
import 'package:smogshield_ai/core/services/gemini_service.dart';
import 'package:smogshield_ai/features/assistant/assistant_screen.dart';

class _TestGeminiService implements GeminiService {
  @override
  Future<AssistantMessage> askQuestion(
    String prompt, {
    Map<String, dynamic>? userContext,
    Map<String, dynamic>? selectedLocation,
    List<AssistantMessage> history = const [],
    String? conversationId,
  }) async {
    return AssistantMessage(
      id: 'test_reply',
      text: 'Gemini test response for $prompt',
      isUser: false,
      timestamp: DateTime.now(),
      engine: 'gemini',
      modelName: 'gemini-test',
      conversationId: conversationId ?? 'test-conversation',
      isMock: false,
    );
  }
}

class _RetryingGeminiService implements GeminiService {
  int calls = 0;

  @override
  Future<AssistantMessage> askQuestion(
    String prompt, {
    Map<String, dynamic>? userContext,
    Map<String, dynamic>? selectedLocation,
    List<AssistantMessage> history = const [],
    String? conversationId,
  }) async {
    calls++;
    if (calls == 1) {
      throw const GeminiServiceUnavailable(
        'Gemini quota is temporarily unavailable.',
      );
    }
    return AssistantMessage(
      id: 'retry_reply',
      text: 'Recovered Gemini response.',
      isUser: false,
      timestamp: DateTime.now(),
      engine: 'gemini',
      isMock: false,
    );
  }
}

void main() {
  Widget buildTestableWidget({GeminiService? service}) {
    return ProviderScope(
      overrides: [
        geminiServiceProvider
            .overrideWithValue(service ?? _TestGeminiService()),
      ],
      child: MaterialApp(
        home: Scaffold(
          body: AssistantScreen(),
        ),
      ),
    );
  }

  testWidgets(
      'Assistant screen displays Gemini notice and initial welcome bubble',
      (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildTestableWidget());
    await tester.pumpAndSettle();

    expect(find.text('AI Assistant'), findsOneWidget);
    expect(find.byKey(const Key('assistant_service_banner')), findsOneWidget);
    expect(find.textContaining('generated by Gemini'), findsOneWidget);
    expect(find.textContaining('Ask about air-quality protection'),
        findsOneWidget);
  });

  testWidgets(
      'Empty-input validation disables Send button and rejects empty submission',
      (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildTestableWidget());
    await tester.pumpAndSettle();

    final sendButtonFinder = find.byKey(const Key('assistant_send_button'));
    final IconButton sendButton = tester.widget(sendButtonFinder);
    expect(sendButton.onPressed, isNull,
        reason: 'Send button should be disabled when input is empty');

    // Enter only whitespace
    final textField = find.byType(TextField);
    await tester.enterText(textField, '     ');
    await tester.pump();

    final IconButton sendButtonAfterSpaces = tester.widget(sendButtonFinder);
    expect(sendButtonAfterSpaces.onPressed, isNull,
        reason: 'Send button should remain disabled for whitespace');

    // Attempt keyboard submission with spaces
    await tester.testTextInput.receiveAction(TextInputAction.send);
    await tester.pump();

    // Verify only the welcome message exists (no empty user message created)
    expect(find.byIcon(Icons.person), findsNothing);
  });

  testWidgets('User can type query and submit via Send button', (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildTestableWidget());
    await tester.pumpAndSettle();

    final textField = find.byType(TextField);
    await tester.enterText(textField, 'Is outdoor jogging safe today?');
    await tester.pump();

    final sendButtonFinder = find.byKey(const Key('assistant_send_button'));
    final IconButton sendButton = tester.widget(sendButtonFinder);
    expect(sendButton.onPressed, isNotNull,
        reason: 'Send button should be enabled after typing text');

    // Tap Send
    await tester.tap(sendButtonFinder);
    await tester.pump();

    // User message bubble appears immediately
    expect(find.text('Is outdoor jogging safe today?'), findsOneWidget);
    expect(find.byIcon(Icons.person), findsOneWidget);

    await tester.pumpAndSettle();

    expect(find.text('Gemini test response for Is outdoor jogging safe today?'),
        findsOneWidget);
  });

  testWidgets('Keyboard submission (TextInputAction.send) submits user message',
      (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildTestableWidget());
    await tester.pumpAndSettle();

    final textField = find.byType(TextField);
    await tester.enterText(textField, 'Which air purifier is best for PM2.5?');
    await tester.pump();
    await tester.testTextInput.receiveAction(TextInputAction.send);
    await tester.pump();

    expect(find.text('Which air purifier is best for PM2.5?'), findsOneWidget);

    await tester.pumpAndSettle();
    expect(
        find.text(
            'Gemini test response for Which air purifier is best for PM2.5?'),
        findsOneWidget);
  });

  testWidgets('Tapping prompt suggestion chip submits the question',
      (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildTestableWidget());
    await tester.pumpAndSettle();

    final suggestionFinder = find.widgetWithText(
      ActionChip,
      'What do the current measurements mean?',
    );
    expect(suggestionFinder, findsOneWidget);

    await tester.tap(suggestionFinder);
    await tester.pump();

    // Query is submitted as user bubble
    expect(find.text('What do the current measurements mean?'), findsWidgets);

    await tester.pumpAndSettle();
    expect(
      find.text(
          'Gemini test response for What do the current measurements mean?'),
      findsOneWidget,
    );
  });

  testWidgets(
      'Unavailable responses can be retried without duplicating the user turn',
      (tester) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(
      buildTestableWidget(service: _RetryingGeminiService()),
    );
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextField), 'What is PM2.5?');
    await tester.pump();
    await tester.tap(find.byKey(const Key('assistant_send_button')));
    await tester.pumpAndSettle();

    expect(
      find.text('Gemini quota is temporarily unavailable.'),
      findsOneWidget,
    );
    expect(find.widgetWithText(TextButton, 'Retry'), findsOneWidget);
    expect(find.text('What is PM2.5?'), findsOneWidget);

    await tester.tap(find.widgetWithText(TextButton, 'Retry'));
    await tester.pumpAndSettle();

    expect(find.text('Recovered Gemini response.'), findsOneWidget);
    expect(find.text('What is PM2.5?'), findsOneWidget);
  });
}
